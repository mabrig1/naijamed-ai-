import { useState } from "react";
import { api } from "../../lib/api";

type Molecule = {
  index: number;
  input_smiles: string;
  valid: boolean;
  error?: string;
  canonical_smiles?: string;
  molecular_formula?: string;
  molecular_weight?: number;
  logp?: number;
  tpsa?: number;
  h_bond_donors?: number;
  h_bond_acceptors?: number;
};

export default function MolecularAnalysis() {
  const [input, setInput] = useState("CCO\nO=C=O");
  const [results, setResults] = useState<Molecule[]>([]);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [projectTitle, setProjectTitle] = useState("");
  const [researcher, setResearcher] = useState("");
  const [methodNotes, setMethodNotes] = useState("");

  async function analyze() {
    const smiles = input.split(/\r?\n/).map(value => value.trim()).filter(Boolean);
    if (!smiles.length || smiles.length > 20 || smiles.some(value => value.length > 2048)) {
      setError("Enter between 1 and 20 SMILES structures, each at most 2,048 characters.");
      setResults([]);
      return;
    }
    setBusy(true);
    setError("");
    setResults([]);
    try {
      const response = await api.post<{ results: Molecule[] }>("/api/research/molecules/analyze", { smiles });
      setResults(response.data.results);
    } catch (reason: unknown) {
      const detail = (reason as { response?: { data?: { detail?: string } } })?.response?.data?.detail;
      setError(detail || "Molecular analysis is unavailable. Sign in and check that the research service is configured.");
    } finally {
      setBusy(false);
    }
  }

  function exportResults() {
    const data = { exported_at: new Date().toISOString(), results, notice: "Research-only descriptors, not ADMET or clinical safety predictions." };
    const url = URL.createObjectURL(new Blob([JSON.stringify(data, null, 2)], { type: "application/json" }));
    const link = document.createElement("a");
    link.href = url;
    link.download = "nigerflora-molecular-descriptors.json";
    link.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  }

  function exportResearchReport() {
    const report = {
      report_type: "Computational Molecular Descriptor Report",
      schema_version: 1,
      project_title: projectTitle.trim() || "Untitled molecular research",
      researcher: researcher.trim() || "Not specified",
      generated_at: new Date().toISOString(),
      methodology: {
        method: "RDKit SMILES parsing and deterministic molecular descriptor calculation",
        software_version: "Not reported by API; record RDKit runtime version before publication",
        structure_standardization: "Canonical isomeric SMILES generated by RDKit; no salt removal or tautomer normalization",
        user_methods_notes: methodNotes,
        measured_endpoints: ["molecular formula", "molecular weight", "calculated LogP", "TPSA", "H-bond donors", "H-bond acceptors"],
      },
      sample_count: results.length,
      valid_structures: results.filter(item => item.valid).length,
      invalid_structures: results.filter(item => !item.valid).length,
      results,
      limitations: [
        "Calculated descriptors are not measured pharmacokinetic or toxicological properties.",
        "No molecular docking, ADMET prediction, toxicity assessment or clinical validation was performed.",
        "Structures and reported outputs require independent scientific review.",
        "Software version and computational environment must be recorded separately for reproducibility."
      ],
    };
    const url = URL.createObjectURL(new Blob([JSON.stringify(report, null, 2)], { type: "application/json" }));
    const link = document.createElement("a");
    link.href = url;
    link.download = "nigerflora-research-report.json";
    link.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  }

  return <section className="card space-y-4" aria-labelledby="molecular-analysis-title">
    <h2 id="molecular-analysis-title" className="text-2xl font-bold text-forest-800">Molecular structure analysis</h2>
    <p className="text-sm text-gray-600">Enter one SMILES string per line (maximum 20). The authenticated research API calculates basic molecular descriptors when RDKit is configured.</p>
    <label className="block text-sm font-medium">SMILES structures
      <textarea className="input mt-1 min-h-28 font-mono text-sm" value={input} onChange={event => setInput(event.target.value)} maxLength={42000} />
    </label>
    <div className="grid gap-3 md:grid-cols-2">
      <label className="block text-sm font-medium">Research project title
        <input className="input mt-1" maxLength={240} value={projectTitle} onChange={event => setProjectTitle(event.target.value)} />
      </label>
      <label className="block text-sm font-medium">Researcher / institution
        <input className="input mt-1" maxLength={240} value={researcher} onChange={event => setResearcher(event.target.value)} />
      </label>
    </div>
    <label className="block text-sm font-medium">Methods notes and provenance
      <textarea className="input mt-1 min-h-24" maxLength={5000} value={methodNotes} onChange={event => setMethodNotes(event.target.value)} placeholder="Document data source, structure preparation and relevant research limitations." />
    </label>
    <button type="button" className="btn-primary" disabled={busy} onClick={() => void analyze()}>{busy ? "Analyzing…" : "Analyze structures"}</button>
    {error && <p role="alert" className="text-sm text-red-700">{error}</p>}
    {results.length > 0 && <>
      <div className="overflow-x-auto">
        <table className="w-full min-w-[680px] text-left text-sm">
          <thead><tr className="border-b"><th className="p-2">Input</th><th className="p-2">Canonical SMILES</th><th className="p-2">Formula</th><th className="p-2">MW</th><th className="p-2">LogP</th><th className="p-2">TPSA</th><th className="p-2">HBD/HBA</th></tr></thead>
          <tbody>{results.map(item => <tr key={item.index} className="border-b">
            <td className="max-w-40 break-all p-2 font-mono">{item.input_smiles}</td>
            {item.valid ? <>
              <td className="max-w-48 break-all p-2 font-mono">{item.canonical_smiles}</td>
              <td className="p-2">{item.molecular_formula}</td>
              <td className="p-2">{item.molecular_weight}</td>
              <td className="p-2">{item.logp}</td>
              <td className="p-2">{item.tpsa}</td>
              <td className="p-2">{item.h_bond_donors}/{item.h_bond_acceptors}</td>
            </> : <td className="p-2 text-red-700" colSpan={6}>{item.error || "Invalid structure"}</td>}
          </tr>)}</tbody>
        </table>
      </div>
      <div className="flex flex-wrap gap-3"><button type="button" className="btn-primary" onClick={exportResults}>Export results (JSON)</button><button type="button" className="btn-primary" onClick={exportResearchReport}>Export research report (JSON)</button></div>
    </>}
    <p className="text-xs text-gray-500">Research use only. Descriptors do not establish ADMET, toxicity, binding affinity, efficacy or clinical safety.</p>
  </section>;
}
